CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    nickname TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE users IS '이력서 서비스의 가입 계정과 세션 인증에 사용하는 사용자 원천.';
COMMENT ON COLUMN users.password_hash IS '서버 전용 BCrypt 해시. API 및 로그에 노출하지 않는다.';

CREATE TABLE IF NOT EXISTS resume (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    title TEXT NOT NULL,
    template TEXT NOT NULL CHECK (template IN ('classic', 'modern')),
    style JSONB NOT NULL CHECK (jsonb_typeof(style) = 'object'),
    content JSONB NOT NULL CHECK (jsonb_typeof(content) = 'array'),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE resume IS '사용자 소유 이력서의 제목, 스타일, 섹션 배열 및 논리 삭제 상태를 저장한다.';
COMMENT ON COLUMN resume.content IS '배열 순서와 숨긴 내용을 보존. photoId는 본인 photo.id의 논리 참조.';
CREATE INDEX IF NOT EXISTS idx_resume_user_deleted_updated_at
    ON resume (user_id, deleted, updated_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS photo (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    content_type TEXT NOT NULL,
    data BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE photo IS '사용자 소유 JPG 또는 PNG 사진 원본을 bytea로 저장한다. 연결 해제 시 물리 삭제하지 않는다.';
CREATE INDEX IF NOT EXISTS idx_photo_user_id
    ON photo (user_id);
