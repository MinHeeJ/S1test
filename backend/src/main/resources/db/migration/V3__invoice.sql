CREATE TABLE IF NOT EXISTS invoice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    doc_type TEXT NOT NULL CHECK (doc_type IN ('quote', 'invoice')),
    doc_no TEXT NOT NULL,
    source_quote_id BIGINT REFERENCES invoice(id) ON DELETE RESTRICT,
    title TEXT NOT NULL,
    content JSONB NOT NULL CHECK (jsonb_typeof(content) = 'object'),
    supply_amount BIGINT NOT NULL CHECK (supply_amount >= 0),
    vat_amount BIGINT NOT NULL CHECK (vat_amount >= 0),
    total_amount BIGINT NOT NULL CHECK (total_amount >= 0),
    paid BOOLEAN NOT NULL DEFAULT FALSE CHECK (doc_type = 'invoice' OR paid = FALSE),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_invoice_user_doc_no UNIQUE (user_id, doc_no)
);
COMMENT ON TABLE invoice IS '사용자 소유 견적서와 청구서의 JSON snapshot 및 서버 계산 금액. 삭제 후에도 번호와 원본 연결을 보존한다.';
COMMENT ON COLUMN invoice.doc_no IS '서버가 사용자·종류·서울 연도별 삭제 포함 MAX+1로 발급; 충돌 시 새 트랜잭션에서 1회 재시도';
COMMENT ON COLUMN invoice.content IS 'stampPhotoId는 photo.id의 논리 참조; 저장 시 애플리케이션에서 본인 사진 소유권 검사';
COMMENT ON COLUMN invoice.supply_amount IS 'InvoiceService가 생성·복제·변환·저장 시 품목과 VAT 방식으로 재계산';
COMMENT ON COLUMN invoice.vat_amount IS 'InvoiceService가 생성·복제·변환·저장 시 정수 나눗셈으로 재계산';
COMMENT ON COLUMN invoice.total_amount IS 'InvoiceService가 생성·복제·변환·저장 시 공급가액과 부가세로 재계산';
COMMENT ON COLUMN invoice.updated_at IS 'InvoiceService가 생성 및 본문 저장 시 갱신; soft delete는 갱신하지 않음';
CREATE INDEX IF NOT EXISTS idx_invoice_user_deleted_updated_at
    ON invoice (user_id, deleted, updated_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_invoice_user_type_deleted_updated_at
    ON invoice (user_id, doc_type, deleted, updated_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_invoice_source_quote_id
    ON invoice (source_quote_id);

