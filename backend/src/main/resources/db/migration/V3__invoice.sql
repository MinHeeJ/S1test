CREATE TABLE IF NOT EXISTS invoice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    doc_type TEXT NOT NULL CHECK (doc_type IN ('quote', 'invoice')),
    doc_no TEXT NOT NULL,
    source_quote_id BIGINT REFERENCES invoice(id) ON DELETE RESTRICT,
    title TEXT NOT NULL,
    content JSONB NOT NULL,
    supply_amount BIGINT NOT NULL CHECK (supply_amount >= 0),
    vat_amount BIGINT NOT NULL CHECK (vat_amount >= 0),
    total_amount BIGINT NOT NULL CHECK (total_amount >= 0),
    paid BOOLEAN NOT NULL DEFAULT FALSE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT invoice_user_id_doc_no_key UNIQUE (user_id, doc_no),
    CONSTRAINT invoice_quote_unpaid_check CHECK (doc_type <> 'quote' OR paid = FALSE)
);
COMMENT ON TABLE invoice IS '사용자 소유 견적서와 청구서의 본문 및 서버 계산 금액. 삭제 후에도 번호와 원본 연결을 보존한다.';
COMMENT ON COLUMN invoice.doc_no IS '서버 생성 Q-YYYY-NNNN 또는 I-YYYY-NNNN; 삭제 포함 사용자·종류·서울 연도별 MAX+1';
COMMENT ON COLUMN invoice.content IS '품목 순서를 보존하는 본문; stampPhotoId는 본인 photo.id의 단일 UUID 또는 null 논리 참조';
COMMENT ON COLUMN invoice.supply_amount IS '생성·복제·변환·저장 시 InvoiceService가 본문으로 재계산하는 공급가액';
COMMENT ON COLUMN invoice.vat_amount IS '생성·복제·변환·저장 시 InvoiceService가 본문으로 재계산하는 부가세';
COMMENT ON COLUMN invoice.total_amount IS '생성·복제·변환·저장 시 InvoiceService가 본문으로 재계산하는 합계';
COMMENT ON COLUMN invoice.updated_at IS '생성 시 DB 기본값; 저장 시 애플리케이션에서 갱신하며 soft delete 시 보존';

CREATE INDEX IF NOT EXISTS idx_invoice_user_deleted_updated_at
    ON invoice (user_id, deleted, updated_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_invoice_user_doc_type_deleted_updated_at
    ON invoice (user_id, doc_type, deleted, updated_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_invoice_source_quote_id
    ON invoice (source_quote_id);

