CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    nickname TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE users IS '가입 및 세션 인증에 사용하는 사용자 계정. 비밀번호는 BCrypt 해시로 보관한다.';

CREATE TABLE IF NOT EXISTS resume (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    title TEXT NOT NULL,
    template TEXT NOT NULL CHECK (template IN ('classic', 'modern')),
    style JSONB NOT NULL,
    content JSONB NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE resume IS '사용자 소유 이력서의 전체 JSON snapshot. 삭제된 행도 본문을 보존하며 조회에서 제외한다.';
COMMENT ON COLUMN resume.updated_at IS 'ResumeService의 모든 변경 명령에서 애플리케이션이 갱신';
COMMENT ON COLUMN resume.content IS '순서 및 숨김 데이터를 보존하는 섹션 배열; photoId는 photo.id의 논리 참조';
CREATE INDEX IF NOT EXISTS idx_resume_user_deleted_updated_at
    ON resume (user_id, deleted, updated_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS photo (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    content_type TEXT NOT NULL CHECK (content_type IN ('image/jpeg', 'image/png')),
    data BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE photo IS '사용자 소유 JPEG 및 PNG 원본 bytes. 이력서 연결 해제 및 삭제 후에도 비파괴 보존한다.';
CREATE INDEX IF NOT EXISTS idx_photo_user_id
    ON photo (user_id);
