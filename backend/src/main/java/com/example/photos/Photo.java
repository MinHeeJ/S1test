package com.example.photos;

import java.util.UUID;

/** Persistence projection of the original image; it is never serialized as a public JSON response. */
public class Photo {
    private UUID id;
    private UUID userId;
    private String contentType;
    private byte[] data;

    public UUID getId() {
        return id;
    }

    public void setId(UUID id) {
        this.id = id;
    }

    public UUID getUserId() {
        return userId;
    }

    public void setUserId(UUID userId) {
        this.userId = userId;
    }

    public String getContentType() {
        return contentType;
    }

    public void setContentType(String contentType) {
        this.contentType = contentType;
    }

    public byte[] getData() {
        return data;
    }

    public void setData(byte[] data) {
        this.data = data;
    }
}
